const ok   = (s) => console.log('✓ ', s);

// =============================================================
// PHASE 0 — copy + path rewrite + content.js regen
// =============================================================
async function phase0() {
  head('Phase 0 — copy & path rewrite');

  // 0a. Regenerate lib/content.js from JSON sources.
  //     The runtime reads content.js synchronously, but slugs and any
  //     other newly-added fields live in JSON. We mirror them into a
  //     thin generated content.js so the runtime + JSON stay in lock
  //     step. JSON is the single source of truth; content.js is an
  //     artifact.
  const enJson = await readFile(join(ROOT, 'data/content.en.json'), 'utf8');
  const heJson = await readFile(join(ROOT, 'data/content.he.json'), 'utf8');
  const en = JSON.parse(enJson);
  const he = JSON.parse(heJson);
  for (const lang of [{ name: 'en', data: en }, { name: 'he', data: he }]) {
    const missing = lang.data.work.projects.filter((p) => !p.slug);
    if (missing.length) {
      throw new Error(
        `data/content.${lang.name}.json: ${missing.length} project(s) missing slug`
      );
    }
  }
  const contentJsBanner =
    '// =============================================================\n' +
    '// lib/content.js — GENERATED FILE\n' +
    '// -------------------------------------------------------------\n' +
    '// This file is REGENERATED by build/build.mjs from\n' +
    '//   data/content.en.json\n' +
    '//   data/content.he.json\n' +
    '// on every build. DO NOT EDIT BY HAND — your changes will be\n' +
    '// overwritten. Edit the JSON sources instead.\n' +
    '// =============================================================\n\n';
  const contentJs =
    contentJsBanner +
    'window.PORTFOLIO_CONTENT = ' +
    JSON.stringify({ en, he }, null, 2) +
    ';\n';
  await writeFile(join(ROOT, 'lib/content.js'), contentJs, 'utf8');
  log(`regenerated lib/content.js from JSON (${(contentJs.length / 1024).toFixed(1)} KB)`);

  // 0b. Read source HTML.
  let html = await readFile(SRC_HTML, 'utf8');
  log(`read prototypes/mono.html (${html.length.toLocaleString()} chars)`);

  // 2. Rewrite paths.
  //    mono.html sits in prototypes/, references ../lib/ and ../*.jsx.
  //    dist/index.html sits at dist root, so:
  //      ../lib/         → lib/
  //      ../tweaks-panel → tweaks-panel
  //      ../design-canv  → design-canvas
  html = html
    .replace(/(["'])\.\.\/lib\//g, '$1lib/')
    .replace(/(["'])\.\.\/tweaks-panel\.jsx/g, '$1tweaks-panel.jsx')
    .replace(/(["'])\.\.\/design-canvas\.jsx/g, '$1design-canvas.jsx');
  log('paths rewritten: ../lib/ → lib/  ·  ../tweaks-panel.jsx → tweaks-panel.jsx');

  // 3. Write dist/index.html.
  await mkdir(DIST, { recursive: true });
  await writeFile(join(DIST, 'index.html'), html, 'utf8');
  ok('dist/index.html');

  // 4. Copy runtime libraries (CSS + JS + content store).
  await mkdir(join(DIST, 'lib'), { recursive: true });
  for (const f of ['core.css', 'core.js', 'content.js', 'content-loader.js', 'fonts-self-hosted.css']) {
    const src = join(ROOT, 'lib', f);
    if (existsSync(src)) {
      await cp(src, join(DIST, 'lib', f));
      ok(`lib/${f}`);
    } else {
      log(`skipped (missing): lib/${f}`);
    }
  }

  // 4b. Copy self-hosted font binaries (woff2). The fonts directory may
  //     contain only a README in development; skip silently if no woff2.
  const fontSrcDir = join(ROOT, 'lib/fonts');
  if (existsSync(fontSrcDir)) {
    await mkdir(join(DIST, 'lib/fonts'), { recursive: true });
    const fontFiles = await readdir(fontSrcDir);
    let copied = 0;
    for (const f of fontFiles) {
      if (!f.endsWith('.woff2')) continue;
      await cp(join(fontSrcDir, f), join(DIST, 'lib/fonts', f));
      copied++;
    }
    if (copied > 0) ok(`lib/fonts/ (${copied} woff2 files)`);
    else log(`lib/fonts/ — no woff2 files yet (using Google Fonts fallback)`);
  }

  // 5. Copy root-level Babel/React component files referenced from the page.
  for (const f of ['tweaks-panel.jsx', 'design-canvas.jsx']) {
    const src = join(ROOT, f);
    if (existsSync(src)) {
      await cp(src, join(DIST, f));
      ok(f);
    }
  }

  // 6. Copy data JSON files (used by content-loader.js).
  await mkdir(join(DIST, 'data'), { recursive: true });
  for (const f of ['content.en.json', 'content.he.json', 'cases.en.json', 'cases.he.json']) {
    const src = join(ROOT, 'data', f);
    if (existsSync(src)) {
      await cp(src, join(DIST, 'data', f));
      ok(`data/${f}`);
    } else {
      log(`skipped (missing): data/${f}`);
    }
  }

  // 7. Copy SEO + brand assets that must live at site root.
  for (const f of [
    'robots.txt',
    'sitemap.xml',
    'site.webmanifest',
    'favicon.svg',
    'favicon.png',
    'apple-touch-icon.png',
    'og.png'
  ]) {
    const src = join(ROOT, f);
    if (existsSync(src)) {
      await cp(src, join(DIST, f));
      ok(f);
    } else {
      log(`skipped (missing): ${f}`);
    }
  }

  // 7b. Copy Cloudflare Pages / Netlify config files from public/ to dist root.
  //     _headers controls caching + security headers; _redirects defines
  //     trailing-slash rules and the catch-all 404 fallback.
  const publicDir = join(ROOT, 'public');
  if (existsSync(publicDir)) {
    for (const f of ['_headers', '_redirects']) {
      const src = join(publicDir, f);
      if (existsSync(src)) {
        await cp(src, join(DIST, f));
        ok(f);
      }
    }
  }

  // 8. Final summary.
  const distFiles = await walk(DIST);
  log('');
  log(`dist/ → ${distFiles.length} files emitted`);
}

// =============================================================
// PHASE 0c — JSX → JS pre-compile (esbuild)
// -------------------------------------------------------------
// Strips <script type="text/babel"> + @babel/standalone from
// the production bundle. Compiles each .jsx → .js, transforms
// every inline text/babel block into plain JS, rewrites <script
// type="text/babel" src="x.jsx"> → <script src="x.js" defer>,
// and removes the dev-only Babel loader gate.
//
// After this phase, grep -r "text/babel" dist/ returns nothing.
// =============================================================
async function phase0c_compileJsx() {
  head('Phase 0c — compile JSX → JS (esbuild)');

  // -- 0c.1 compile each loose .jsx file in dist/ root --
  const distFiles = await readdir(DIST);
  const jsxFiles = distFiles.filter((f) => f.endsWith('.jsx'));
  for (const jsx of jsxFiles) {
    const src = await readFile(join(DIST, jsx), 'utf8');
    const out = await esbuild.transform(src, {
      loader: 'jsx',
      jsx: 'transform',                       // classic React.createElement
      jsxFactory: 'React.createElement',      // matches global React UMD
      jsxFragment: 'React.Fragment',
      target: ['es2018'],                     // safe for all modern browsers
      sourcemap: false,
      legalComments: 'none',
    });
    const jsName = jsx.replace(/\.jsx$/, '.js');
    await writeFile(join(DIST, jsName), out.code, 'utf8');
    await unlink(join(DIST, jsx));
    log(`compiled ${jsx} → ${jsName} (${(out.code.length / 1024).toFixed(1)} KB)`);
  }

  // -- 0c.2 rewrite dist/index.html: <script type="text/babel"> → plain --
  const indexPath = join(DIST, 'index.html');
  let html = await readFile(indexPath, 'utf8');
  const before = html.length;

  // Park HTML comments before regex passes. Comments may legitimately
  // contain the literal string `<script type="text/babel">` (in docs
  // or rationale), and our non-greedy regex would otherwise match
  // across the comment closing into real code.
  const commentSlots = [];
  html = html.replace(/<!--[\s\S]*?-->/g, (m) => {
    commentSlots.push(m);
    return `__BUILD_COMMENT_${commentSlots.length - 1}__`;
  });

  // Inline <script type="text/babel">…</script> → compiled inline <script>
  html = await replaceAsync(
    html,
    /<script\s+type="text\/babel">([\s\S]*?)<\/script>/g,
    async (_match, body) => {
      const out = await esbuild.transform(body, {
        loader: 'jsx',
        jsx: 'transform',
        jsxFactory: 'React.createElement',
        jsxFragment: 'React.Fragment',
        target: ['es2018'],
        legalComments: 'none',
      });
      return `<script>${out.code}</script>`;
    }
  );

  // External <script type="text/babel" src="x.jsx"> → <script src="x.js">.
  // Intentionally NOT defer: tweaks-panel.js installs window.TweaksPanel etc.
  // as a side effect, and the following inline <script> block consumes
  // those globals during parse. Defer would invert that ordering.
  html = html.replace(
    /<script\s+type="text\/babel"\s+src="([^"]+)\.jsx"[^>]*><\/script>/g,
    '<script src="$1.js"></script>'
  );

  // Strip the dev-only Babel gate (the <script>…isLocal…@babel/standalone…</script>
  // we inject in prototypes/mono.html for in-place .jsx editing). In dist/ all
  // JSX has been pre-compiled, so the gate would only ever no-op.
  html = html.replace(
    /<script>\s*\(function\s*\(\)\s*\{[^]*?@babel\/standalone[^]*?\}\)\(\);\s*<\/script>/g,
    ''
  );

  // Restore parked HTML comments.
  html = html.replace(/__BUILD_COMMENT_(\d+)__/g, (_, i) => commentSlots[Number(i)]);

  await writeFile(indexPath, html, 'utf8');
  ok(`dist/index.html JSX-free (${before.toLocaleString()} → ${html.length.toLocaleString()} chars)`);
}

// =============================================================
// PHASE 0e — strip dev-only React UMD + tweaks-panel from prod
// -------------------------------------------------------------
// tweaks-panel.jsx is a dev tooling panel that only activates on
// localhost / ?debug=1. It depends on React + ReactDOM (UMD from
// unpkg.com — combined ~47 KB transfer, ~143 KB unpacked).
//
// In production neither the panel nor React are ever instantiated,
// but the <script> tags still ship and the browser still fetches +
// parses both UMDs. Lighthouse 2026-05-19 flagged 23 KB unused
// react-dom (53.7%) and gave 270 ms script parse/compile time to
// these never-used scripts.
//
// This phase removes:
//   • <script src="…unpkg.com/react…"> + react-dom (2 tags)
//   • <script src="tweaks-panel.js" …> + <div id="tweaks-root">
//   • <script src="…babel.min.js…"> (defensive — the Babel gate
//     in phase0c usually catches this, but stripping the URL too
//     defends against future template drift)
//   • dist/tweaks-panel.js and dist/design-canvas.js (unlinked)
//
// Runs AFTER phase0c (JSX is compiled to plain JS, the runtime
// no longer needs React.createElement to resolve) and BEFORE
// phase7_extractInlineJs so the extracted main.js doesn't have
// to handle the React-script-removal as a string patch.
// =============================================================
async function phase0e_stripDevDeps() {
  head('Phase 0e — strip React UMD + tweaks-panel (dev-only, never used in prod)');

  const indexFiles = ['index.html', 'he/index.html'];
  let totalRemovedLines = 0;
  for (const rel of indexFiles) {
    const p = join(DIST, rel);
    if (!existsSync(p)) continue;
    let html = await readFile(p, 'utf8');
    const before = html.length;

    // Remove the surrounding HTML comment block that documents these scripts,
    // so the resulting <head> stays clean. Conservative match — only the
    // exact "React/ReactDOM: production-min UMD" comment that wraps the tags.
    html = html.replace(
      /<!--\s*React\/ReactDOM:[\s\S]*?-->\s*\n?/g,
      ''
    );

    // <script src="…unpkg.com/react…"> and <script src="…unpkg.com/react-dom…">
    html = html.replace(
      /<script[^>]*\bsrc="https?:\/\/unpkg\.com\/react(?:-dom)?@[^"]*"[^>]*><\/script>\s*\n?/g,
      ''
    );

    // <script src="https://unpkg.com/@babel/standalone@…"> (defensive)
    html = html.replace(
      /<script[^>]*\bsrc="https?:\/\/unpkg\.com\/@babel\/standalone@[^"]*"[^>]*><\/script>\s*\n?/g,
      ''
    );

    // Comment block describing the dev-only tweaks-panel.jsx gate (preceding
    // the tweaks-panel script tag in the source).
    html = html.replace(
      /<!--\s*tweaks-panel\.jsx is dev-only tooling[\s\S]*?-->\s*\n?/g,
      ''
    );

    // <script src="tweaks-panel.js" …> + <script src="design-canvas.js" …>.
    // We only match local refs (no scheme) to avoid touching unrelated CDN
    // scripts that might happen to share the basename.
    html = html.replace(
      /<script[^>]*\bsrc="(?:tweaks-panel|design-canvas)\.js"[^>]*><\/script>\s*\n?/g,
      ''
    );

    // The empty React root that tweaks-panel would have mounted into.
    html = html.replace(
      /<div\s+id="tweaks-root">\s*<\/div>\s*\n?/g,
      ''
    );

    if (html.length !== before) {
      await writeFile(p, html, 'utf8');
      const removedLines = (before - html.length);
      totalRemovedLines += removedLines;
      log(`${rel}: stripped ${removedLines.toLocaleString()} bytes of dev-only script refs`);
    } else {
      log(`${rel}: no dev-only refs found (already stripped?)`);
    }
  }

  // Physically delete the JS files so even a stray <link rel="preload"> or
  // direct URL fetch returns 404. Cache-bust phase already ran on the HTML,
  // but the artifacts on disk are now orphaned.
  for (const f of ['tweaks-panel.js', 'design-canvas.js']) {
    const p = join(DIST, f);
    if (existsSync(p)) {
      await unlink(p);
      log(`unlinked dist/${f}`);
    }
  }

  ok(`React + tweaks-panel removed from production (total: ${totalRemovedLines.toLocaleString()} bytes from HTML + 2 JS files)`);
}

// Small async replace helper — String.replace doesn't await async callbacks.
async function replaceAsync(str, regex, asyncFn) {
  const promises = [];
  str.replace(regex, (match, ...args) => {
    promises.push(asyncFn(match, ...args));
    return match;
  });
  const data = await Promise.all(promises);
  return str.replace(regex, () => data.shift());
}

// =============================================================
// PHASE 0d — minify CSS + JS in dist/ (esbuild)
// -------------------------------------------------------------
// Runs after JSX compile so the compiled .js files are also
// minified. Lighthouse flagged site.css (53 KB savings) and
// content.js/core.js (4-8 KB each) as un-minified.
// =============================================================
async function phase0d_minify() {
  head('Phase 0d — minify CSS + JS');

  const targets = [
    { path: 'lib/site.css',      loader: 'css' },
    { path: 'lib/core.css',      loader: 'css' },
    { path: 'lib/fonts-self-hosted.css', loader: 'css' },
    { path: 'lib/core.js',       loader: 'js'  },
    { path: 'lib/content.js',    loader: 'js'  },
    { path: 'lib/content-loader.js', loader: 'js' },
    { path: 'lib/main.js',       loader: 'js'  }, // extracted in phase 7
    { path: 'tweaks-panel.js',   loader: 'js'  },
    { path: 'design-canvas.js',  loader: 'js'  },
  ];

  for (const t of targets) {
    const p = join(DIST, t.path);
    if (!existsSync(p)) continue;
    const src = await readFile(p, 'utf8');
    const out = await esbuild.transform(src, {
      loader: t.loader,
      minify: true,
      target: t.loader === 'css' ? ['chrome90', 'firefox88', 'safari14'] : ['es2018'],
      legalComments: 'none',
      // Keep Hebrew/RTL characters as UTF-8 rather than \uXXXX escapes —
      // א is 6 bytes per Hebrew letter vs 2 bytes UTF-8, so without
      // this the bilingual content.js GROWS rather than shrinks.
      charset: 'utf8',
    });
    await writeFile(p, out.code, 'utf8');
    const saved = ((1 - out.code.length / src.length) * 100).toFixed(1);
    log(`minified ${t.path}: ${(src.length / 1024).toFixed(1)} → ${(out.code.length / 1024).toFixed(1)} KB (−${saved}%)`);
  }
  ok('CSS + JS minified');
}

// =============================================================
// PHASE — content-hash cache-bust for /lib/* assets
// -------------------------------------------------------------
// /lib/* is shipped with `Cache-Control: immutable, max-age=1yr`,
// but filenames don't change between builds. So browsers that
// cached lib/main.js never refetch it — they hold the old bytes
// for a year, even after a deploy. Fix: append ?v=<8-char-md5>
// to every lib/* href/src in dist HTML. Same filename on disk
// (Cloudflare still serves it), but the URL is different — so
// the cache key is different, so the browser refetches.
//
// Runs AFTER phase0d_minify so hashes reflect final shipped bytes.
// =============================================================
async function phase_cacheBust() {
  head('Phase — cache-bust /lib/* via content-hash');

  const libFiles = [
    'lib/main.js', 'lib/core.js', 'lib/content.js', 'lib/content-loader.js',
    'lib/core.css', 'lib/site.css', 'lib/fonts-self-hosted.css',
  ];
  const versions = {};
  for (const f of libFiles) {
    const p = join(DIST, f);
    if (!existsSync(p)) continue;
    const c = await readFile(p);
    versions[f] = createHash('md5').update(c).digest('hex').slice(0, 8);
  }

  async function walk(dir, files = []) {
    for (const ent of await readdir(dir, { withFileTypes: true })) {
      const p = join(dir, ent.name);
      if (ent.isDirectory()) await walk(p, files);
      else if (ent.name.endsWith('.html')) files.push(p);
    }
    return files;
  }
  const htmlFiles = await walk(DIST);

  let totalRewrites = 0;
  for (const htmlPath of htmlFiles) {
    let html = await readFile(htmlPath, 'utf8');
    for (const [f, v] of Object.entries(versions)) {
      const base = f.split('/').pop().replace(/\./g, '\\.');
      // Match attr="…lib/<file>" with NO existing query string. The
      // negative lookahead (?!\?) prevents double-stamping if a build
      // is re-run against already-stamped HTML.
      const re = new RegExp(
        `(["'])((?:\\.\\.\\/)?lib\\/${base})(?!\\?)\\1`,
        'g'
      );
      html = html.replace(re, (match, quote, path) => {
        totalRewrites++;
        return `${quote}${path}?v=${v}${quote}`;
      });
    }
    await writeFile(htmlPath, html, 'utf8');
  }
  ok(`cache-bust appended to ${totalRewrites} reference(s) across ${htmlFiles.length} HTML file(s)`);
}

// =============================================================
// PHASE 1 — pre-render
//   Replaces the inner content of every container the runtime JS
//   used to fill via innerHTML. After this phase, all 10 sections
//   ship inside the initial HTML payload — grep-able, indexable,
//   visible without JS.
//
//   The runtime JS in mono.html stays in place: when it runs, it
//   reassigns innerHTML with byte-identical content (same data,
//   same lang). No visible flicker. Language toggle still works.
// =============================================================
async function phase1() {
  head('Phase 1 — pre-render');

  const content = JSON.parse(
    await readFile(join(ROOT, 'data/content.en.json'), 'utf8')
  );
  const indexPath = join(DIST, 'index.html');
  let html = await readFile(indexPath, 'utf8');
  const before = html.length;

  for (const section of SECTIONS) {
    const rendered = section.render(content);
    html = injectIntoContainer(html, section.id, rendered);
    log(`pre-rendered #${section.id.padEnd(15)} ${rendered.length.toLocaleString().padStart(8)} chars`);
  }

  // Remove the <noscript> fallback — obsolete now that the content
  // is in the initial HTML for every crawler, not just JS-running ones.
  const noscriptRE = /\n\n<!-- ===================== NOSCRIPT FALLBACK[\s\S]*?<\/noscript>\n/;
  if (noscriptRE.test(html)) {
    html = html.replace(noscriptRE, '\n');
    log('removed <noscript> fallback (obsolete after pre-render)');
  }

  await writeFile(indexPath, html, 'utf8');
  ok(`dist/index.html pre-rendered (${before.toLocaleString()} → ${html.length.toLocaleString()} chars)`);
}

// -------- injection helper --------
// Finds <TAG ... id="ID" ...>...</TAG> and replaces inner content.
// Uses a depth-tracking scanner (regex isn't safe across nested tags).
function injectIntoContainer(html, id, content) {
  const idMarker = `id="${id}"`;
  const idIdx = html.indexOf(idMarker);
  if (idIdx === -1) throw new Error(`Container #${id} not found in HTML`);

  // Walk left from id="X" to find the '<' starting the tag.
  let tagStart = idIdx;
  while (tagStart > 0 && html[tagStart] !== '<') tagStart--;

  // Walk right from id="X" to find the '>' closing the open tag.
  let tagEnd = idIdx;
  while (tagEnd < html.length && html[tagEnd] !== '>') tagEnd++;
  if (tagEnd >= html.length) throw new Error(`No closing '>' for #${id}`);

  // Extract tag name (e.g. 'div').
  const tagMatch = html.slice(tagStart + 1, tagEnd).match(/^(\w+)/);
  if (!tagMatch) throw new Error(`Cannot parse tag name for #${id}`);
  const tagName = tagMatch[1];

  // Scan forward, tracking depth of <tagName>...</tagName> pairs.
  // Self-closing form (`<div />`) isn't used in this codebase so we
  // don't special-case it. (HTML <br>, <img> etc. don't share names.)
  const openRE  = new RegExp(`<${tagName}\\b`, 'gi');
  const closeRE = new RegExp(`</${tagName}\\s*>`, 'gi');
  let depth = 1;
  let cursor = tagEnd + 1;

  while (cursor < html.length && depth > 0) {
    openRE.lastIndex = cursor;
    closeRE.lastIndex = cursor;
    const openMatch  = openRE.exec(html);
    const closeMatch = closeRE.exec(html);

    if (!closeMatch) throw new Error(`Unbalanced <${tagName}> at #${id}`);

    if (openMatch && openMatch.index < closeMatch.index) {
      depth++;
      cursor = openMatch.index + openMatch[0].length;
    } else {
      depth--;
      if (depth === 0) {
        // closeMatch.index = start of </tagName>
        return html.slice(0, tagEnd + 1) + content + html.slice(closeMatch.index);
      }
      cursor = closeMatch.index + closeMatch[0].length;
    }
  }
  throw new Error(`No matching </${tagName}> for #${id}`);
}

